const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('../web/node_modules/typescript');
const previous = require.extensions['.ts'];
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, file);
const {changeGame, currentPlayer: me, spots, validateGame} = require('./games.ts');
const {demoGames, defaultInput} = require('./demo.ts');
const {createDemoService} = require('./demo-service.ts');
(async () => {
 const [football, cricket, hosted, padel] = demoGames();
 assert.throws(()=>changeGame({...football,startsAt:'2000-01-01'},me,{type:'join'}),/already started/);
 const joined = changeGame(football, me, {type:'join'});
 assert.equal(spots(joined), spots(football)-1);
 assert.throws(()=>changeGame(joined, me, {type:'join'}), /already/);
 assert.equal(changeGame(joined, me, {type:'leave'}).players.length, football.players.length);
 const requested = changeGame(cricket, me, {type:'join'});
 assert(requested.requests.some(p=>p.id===me.id));
 assert.equal(requested.players.length, cricket.players.length);
 assert.throws(()=>changeGame(requested, me, {type:'join'}), /already/);
 assert.equal(changeGame(requested,me,{type:'leave'}).requests.length,0);
 const approved=changeGame(hosted,me,{type:'approve',playerId:'sara'});
 assert(approved.players.some(p=>p.id==='sara'));
 assert.equal(approved.requests.length,1);
 assert.equal(approved.requests[0].id,'hamza');
 assert.equal(changeGame(hosted,me,{type:'reject',playerId:'sara'}).requests.length,1);
 assert.throws(()=>changeGame(football,me,{type:'cancel'}),/host/);
 assert.throws(()=>changeGame(football,me,{type:'edit',input:defaultInput}),/host/);
 assert.throws(()=>changeGame(hosted,me,{type:'leave'}),/Hosts/);
 const full={...hosted,maxPlayers:hosted.players.length};
 assert.throws(()=>changeGame(full,me,{type:'approve',playerId:'sara'}),/full/);
 assert.throws(()=>changeGame({...football,maxPlayers:football.players.length},me,{type:'join'}),/full/);
 assert.throws(()=>changeGame({...football,status:'cancelled'},me,{type:'join'}),/no longer/);
 assert.equal(changeGame(hosted,me,{type:'cancel'}).requests.length,0);
 assert.throws(()=>changeGame(hosted,me,{type:'edit',input:{...defaultInput,maxPlayers:1}}));
 for(const bad of [{title:''},{latitude:91},{longitude:181},{maxPlayers:2.5},{duration:0},{startsAt:'bad'},{startsAt:'2000-01-01'},{joinMode:'captain'}])assert.throws(()=>validateGame({...defaultInput,...bad}));
 assert.equal(changeGame(padel,me,{type:'leave'}).players.length,1);
 const api=createDemoService();const created=await api.create(defaultInput);assert.equal(created.hostId,me.id);assert.equal(created.players.length,1);await api.update(created.id,{type:'cancel'});assert.equal((await api.list()).find(g=>g.id===created.id).status,'cancelled');
 console.log('PASS: joins, requests, approvals, rejection, leave, capacity, permissions, validation, cancellation and demo service');
})().finally(()=>{if(previous)require.extensions['.ts']=previous;else delete require.extensions['.ts'];});
